import { writeFile } from 'node:fs/promises'
import { join, sep } from 'path'

import { afterEach, beforeEach, describe, expect, test } from 'vitest'

import { getBuildInfo } from '../src/node/get-build-info.js'

import { createFixture } from './helpers.js'

afterEach(async ({ cleanup }) => await cleanup?.())

describe('Yarn Workspaces with yarn berry', () => {
  beforeEach(async (ctx) => {
    await createFixture('yarn-berry-workspace', ctx)
  })

  test('should detect a regular yarn workspace from a package level', async ({ cwd }) => {
    const info = await getBuildInfo({ projectDir: 'packages/website', rootDir: cwd })
    expect(info.packageManager?.name).toBe('yarn')
    expect(info.jsWorkspaces?.isRoot).toBe(false)
    expect(info.jsWorkspaces?.packages).toEqual([
      { path: join('packages/blog'), name: '@evilcorp/blog' },
      { path: join('packages/website'), name: '@evilcorp/website' },
    ])
    expect(info.jsWorkspaces?.rootDir).toBe(cwd)
  })

  test('should detect a regular yarn workspace from the root level', async ({ cwd }) => {
    const info = await getBuildInfo({ projectDir: cwd })
    expect(info.packageManager?.name).toBe('yarn')
    expect(info.jsWorkspaces?.isRoot).toBe(true)
    expect(info.jsWorkspaces?.packages).toEqual([
      { path: join('packages/blog'), name: '@evilcorp/blog' },
      { path: join('packages/website'), name: '@evilcorp/website' },
    ])
    expect(info.jsWorkspaces?.rootDir).toBe(cwd)
  })
})

test('should detect a regular yarn project with a lock file in the root', async (ctx) => {
  const fixture = await createFixture('yarn-project', ctx)
  const info = await getBuildInfo({ projectDir: '', rootDir: fixture.cwd })
  expect(info.packageManager?.name).toBe('yarn')
})

test('should detect a regular yarn project that is nested in a sub-folder', async (ctx) => {
  const fixture = await createFixture('yarn-nested', ctx)
  const info = await getBuildInfo({ projectDir: `projects${sep}website`, rootDir: fixture.cwd })
  expect(info.packageManager?.name).toBe('yarn')
})

test('should detect yarn 1 from classic yarn.lock', async (ctx) => {
  const fixture = await createFixture('yarn-project', ctx)
  await writeFile(
    join(fixture.cwd, 'yarn.lock'),
    '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n',
  )
  const info = await getBuildInfo({ projectDir: '', rootDir: fixture.cwd })
  expect(info.packageManager?.name).toBe('yarn')
  expect(info.packageManager?.version?.major).toBe(1)
})

test('should detect yarn 3 from berry metadata version 6', async (ctx) => {
  const fixture = await createFixture('yarn-project', ctx)
  await writeFile(join(fixture.cwd, 'yarn.lock'), '__metadata:\n  version: 6\n  cacheKey: 8\n')
  const info = await getBuildInfo({ projectDir: '', rootDir: fixture.cwd })
  expect(info.packageManager?.name).toBe('yarn')
  expect(info.packageManager?.version?.major).toBe(3)
})

test('should detect yarn 4 from berry metadata version 8', async (ctx) => {
  const fixture = await createFixture('yarn-project', ctx)
  await writeFile(join(fixture.cwd, 'yarn.lock'), '__metadata:\n  version: 8\n  cacheKey: 10c0\n')
  const info = await getBuildInfo({ projectDir: '', rootDir: fixture.cwd })
  expect(info.packageManager?.name).toBe('yarn')
  expect(info.packageManager?.version?.major).toBe(4)
})

test('should detect exact yarn version from .yarnrc.yml yarnPath', async (ctx) => {
  const fixture = await createFixture('yarn-project', ctx)
  await writeFile(join(fixture.cwd, 'yarn.lock'), '__metadata:\n  version: 6\n')
  await writeFile(join(fixture.cwd, '.yarnrc.yml'), 'yarnPath: .yarn/releases/yarn-3.6.4.cjs\n')
  const info = await getBuildInfo({ projectDir: '', rootDir: fixture.cwd })
  expect(info.packageManager?.name).toBe('yarn')
  expect(info.packageManager?.version?.raw).toBe('3.6.4')
})

test('should detect exact yarn version with .js extension and ignore commented lines', async (ctx) => {
  const fixture = await createFixture('yarn-project', ctx)
  await writeFile(join(fixture.cwd, 'yarn.lock'), '__metadata:\n  version: 6\n')
  await writeFile(
    join(fixture.cwd, '.yarnrc.yml'),
    '# yarnPath: .yarn/releases/yarn-2.4.0.cjs\nyarnPath: .yarn/releases/yarn-4.1.0.js\n',
  )
  const info = await getBuildInfo({ projectDir: '', rootDir: fixture.cwd })
  expect(info.packageManager?.name).toBe('yarn')
  expect(info.packageManager?.version?.raw).toBe('4.1.0')
})


