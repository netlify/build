import { mkdir, writeFile } from 'fs/promises'
import { basename, join, resolve } from 'path'

import { findServerEntry } from '@netlify/zip-it-and-ship-it'

import { addErrorInfo } from '../../error/info.js'
import { type FeatureFlags } from '../../core/feature_flags.js'
import { FRAMEWORKS_API_SERVER_PATH } from '../../utils/frameworks_api.js'
import { pathExists } from '../../utils/path_exists.js'

// Where a site's server lives, relative to the package root.
export const SERVER_DIRECTORY = 'netlify/server'

export const useServerAsFunction = (featureFlags?: FeatureFlags): boolean =>
  featureFlags?.netlify_build_server_entry === true && !useServerStandalone(featureFlags)

export const useServerStandalone = (featureFlags?: FeatureFlags): boolean =>
  featureFlags?.netlify_build_server_standalone === true

export interface ServerEntry {
  // Path of the server entrypoint.
  entryPath: string

  // Root of the package the server belongs to.
  packageRoot: string

  // Directory holding the entrypoint, relative to the package root.
  relativeDirectory: string

  // Entrypoint path relative to the package root, for logging.
  relativeEntryPath: string
}

const findServerEntryIn = async (packageRoot: string, relativeDirectory: string): Promise<ServerEntry | undefined> => {
  const entryPath = await findServerEntry(join(packageRoot, relativeDirectory))

  if (entryPath === undefined) {
    return undefined
  }

  return {
    entryPath,
    packageRoot,
    relativeDirectory,
    relativeEntryPath: `${relativeDirectory}/${basename(entryPath)}`,
  }
}

/**
 * Finds the server entrypoint, either in the user's server directory or in the
 * one frameworks write to. A project has one server, so it is a user error for
 * both directories to have an entrypoint.
 */
export const getServerEntry = async ({
  buildDir,
  packagePath,
}: {
  buildDir: string
  packagePath?: string
}): Promise<ServerEntry | undefined> => {
  const packageRoot = resolve(buildDir, packagePath ?? '')

  const [userEntry, frameworkEntry] = await Promise.all([
    findServerEntryIn(packageRoot, SERVER_DIRECTORY),
    findServerEntryIn(packageRoot, FRAMEWORKS_API_SERVER_PATH),
  ]).catch((error: unknown) => {
    addErrorInfo(error, { type: 'resolveConfig' })

    throw error
  })

  if (userEntry !== undefined && frameworkEntry !== undefined) {
    const error = new Error(
      `Found a Netlify Server in ${userEntry.relativeEntryPath} and another one generated by your framework in ${frameworkEntry.relativeEntryPath}. A project can have one server only, so remove ${SERVER_DIRECTORY} to deploy the one your framework generates, or configure your framework not to generate one.`,
    )

    addErrorInfo(error, { type: 'resolveConfig' })

    throw error
  }

  return userEntry ?? frameworkEntry
}

// Whether either server directory exists. It can be created by the build
// command or by a plugin, so steps check it when they are about to run.
export const hasServerDirectory = async ({
  buildDir,
  packagePath,
}: {
  buildDir: string
  packagePath?: string
}): Promise<boolean> => {
  const packageRoot = resolve(buildDir, packagePath ?? '')
  const exists = await Promise.all(
    [SERVER_DIRECTORY, FRAMEWORKS_API_SERVER_PATH].map((directory) => pathExists(join(packageRoot, directory))),
  )

  return exists.some(Boolean)
}

// Everything below carries a server through the functions plumbing, which is
// how it was deployed before it stood on its own. It goes away once no deploy
// is built with the function channel on.

const SERVER_FUNCTION_NAME = '___netlify-server'
const SERVER_SHIM_DIR = '.netlify/server-entry'

// Gives the server the deploy surface of a function without touching the user's
// code, so that it can be bundled and uploaded as one.
const getShimContents = (entryPath: string) => `import * as server from ${JSON.stringify(entryPath)}

export default server.default ?? server

export const config = {
  name: "Netlify Server",
  generator: "netlify-server",
  path: "/*",
  preferStatic: true,
}
`

/**
 * Writes the file a server is bundled from when it travels as a function, and
 * returns its path.
 */
export const writeServerShim = async ({ entryPath, packageRoot }: ServerEntry): Promise<string> => {
  const shimDir = join(packageRoot, SERVER_SHIM_DIR)

  await mkdir(shimDir, { recursive: true })

  const shimPath = join(shimDir, `${SERVER_FUNCTION_NAME}.mjs`)

  await writeFile(shimPath, getShimContents(entryPath))

  return shimPath
}
