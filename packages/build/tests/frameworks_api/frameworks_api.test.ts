test('Does not create dist file when skew protection file is missing', async () => {
  const fixture = new Fixture(import.meta.url, './fixtures/skew_protection_missing')
  const { success } = await fixture.runWithBuildAndIntrospect()
  const distPath = resolve(fixture.repositoryRoot, '.netlify/deploy-config/deploy-config.json')
  expect(success).toBe(true)

  await expect(fs.access(distPath)).rejects.toMatchObject({ code: 'ENOENT' })
})

test('Creates dist file when valid skew protection configuration is provided', async () => {
  const fixture = new Fixture(import.meta.url, './fixtures/skew_protection_valid')
  const { success } = await fixture.runWithBuildAndIntrospect()
  const distPath = resolve(fixture.repositoryRoot, '.netlify/deploy-config/deploy-config.json')

  expect(success).toBe(true)

  const distContent = await fs.readFile(distPath, 'utf8')

  expect(JSON.parse(distContent)).toEqual({
    skew_protection: {
      patterns: ['/api/*', '/dashboard/*'],
      sources: [
        { type: 'cookie', name: 'nf_deploy_id' },
        { type: 'header', name: 'x-nf-deploy-id' },
        { type: 'query', name: 'deploy_id' },
      ],
    },
  })
})
