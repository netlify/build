test('Loads configuration data that has been generated by the build command', async () => {
  const systemLogFile = await tmp.file()
  const { netlifyConfig } = await new Fixture(import.meta.url, './fixtures/from_build_command')
    .withFlags({
      debug: false,
      systemLogFile: systemLogFile.fd,
    })
    .runWithBuildAndIntrospect()

  expect(netlifyConfig?.functions).toEqual({
    '*': {},
    'my_framework*': {
      included_files: ['files/**'],
    },
  })
  expect(netlifyConfig?.images).toEqual({
    remote_images: [
      'domain1.from-toml.netlify',
      'domain2.from-toml.netlify',
      'domain1.from-api.netlify',
      'domain2.from-api.netlify',
    ],
  })
  expect(netlifyConfig?.redirects).toEqual([
    {
      from: '/from-config-override',
      query: {},
      to: '/to-config-override',
      status: 418,
      force: true,
      conditions: {},
      headers: {},
    },
    {
      from: '/from-config',
      query: {},
      to: '/to-config',
      status: 418,
      force: true,
      conditions: {},
      headers: {},
    },
  ])

  // No file descriptors on Windows, so system logging doesn't work.
  if (platform !== 'win32') {
    const systemLog = await fs.readFile(systemLogFile.path, { encoding: 'utf8' })
    const expectedProperties = ['images.remote_images', 'functions.my_framework*', 'redirects']

    expectedProperties.forEach((property) => {
      expect(systemLog).toContain(`Netlify configuration property "${property}" value changed to`)
    })
  }
})

test('Honors `edge_functions` declared through the Frameworks API config file', async () => {
  const { netlifyConfig, success } = await new Fixture(
    import.meta.url,
    './fixtures/edge_functions_config',
  ).runWithBuildAndIntrospect()

  expect(success).toBe(true)
  // Framework-declared edge functions are merged with the ones defined in
  // `netlify.toml`. As with `redirects`, user-defined values take precedence
  // and are evaluated first. All supported properties (including `name` and
  // `generator`, which frameworks like SvelteKit's adapter emit) are preserved.
  expect(netlifyConfig?.edge_functions).toEqual([
    { path: '/from-toml', function: 'user_edge' },
    {
      function: 'my_framework_edge',
      name: 'My framework edge function',
      generator: 'package-name@1.2.3',
      path: '/from-api/*',
      excludedPath: ['/from-api/static/*', '/from-api/skip'],
      cache: 'manual',
      method: ['GET', 'POST'],
      header: { 'x-custom': true },
    },
  ])
})

test('Loads configuration data that has been generated by the build command using the legacy API path', async () => {
  const expectedImageDomains = [
    'domain1.from-toml.netlify',
    'domain2.from-toml.netlify',
    'domain1.from-api.netlify',
    'domain2.from-api.netlify',
  ]
  const systemLogFile = await tmp.file()
  const { netlifyConfig } = await new Fixture(import.meta.url, './fixtures/from_build_command_legacy')
    .withFlags({
      debug: false,
      systemLogFile: systemLogFile.fd,
    })
    .runWithBuildAndIntrospect()

  expect(netlifyConfig?.images).toEqual({
    remote_images: expectedImageDomains,
  })

  if (platform !== 'win32') {
    const systemLog = await fs.readFile(systemLogFile.path, { encoding: 'utf8' })
    const match = /Netlify configuration property "images.remote_images" value changed to \[(.*)\]/s.exec(systemLog)
    assert.isNotNull(match)
    expect(JSON.parse(`[${match[1].replace(/'/g, '"')}]`)).toEqual(expectedImageDomains)
  }
})

